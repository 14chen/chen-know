import { launch, newPage, uiLogin, api, BASE, sleep } from './e4-lib.mjs';
const browser = await launch();
const { ctx, page } = await newPage(browser);
const wire = [];
page.on('request', (r) => { if (r.url().includes('/api/')) wire.push('REQ ' + r.method() + ' ' + r.url().replace(BASE, '') + (r.method() === 'PATCH' ? ' body=' + String(r.postData() || '').slice(0, 120) : '')); });
page.on('response', (r) => { if (r.url().includes('/api/')) wire.push('RES ' + r.status() + ' ' + r.request().method() + ' ' + r.url().replace(BASE, '')); });
await uiLogin(page, 'alice', 'alice12345');
const mk = await api(ctx, 'POST', '/api/notes', { title: '线缆验证', content: '初始内容X' });
const id = mk.body.id;
await page.goto(BASE + '/#/notes/' + id, { waitUntil: 'domcontentloaded' });
await page.waitForSelector('.cm-content'); await sleep(1200);
wire.length = 0;
await page.locator('.cm-content').click();
await page.keyboard.press('Control+End');
await page.keyboard.type(' UI追加ABC');
await sleep(5000);
console.log('—— 输入后 5s 内的 API 流量 ——');
console.log(wire.filter((x) => /PATCH|notes/.test(x)).slice(0, 12).join('\n') || 'NO /api/notes TRAFFIC');
const draft = await page.evaluate(() => Object.keys(localStorage).map((k) => k + '=' + String(localStorage.getItem(k)).length + 'B'));
console.log('LOCALSTORAGE=' + JSON.stringify(draft));
const after = await api(ctx, 'GET', '/api/notes/' + id);
console.log('server_content=' + JSON.stringify(after.body.content).slice(0, 120) + ' version=' + after.body.version);
await ctx.close(); await browser.close();
