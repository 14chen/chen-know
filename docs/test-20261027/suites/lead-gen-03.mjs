L.push("| 结论 | 通过 / 失败 / 阻塞（阻塞=环境或前置不具备，已附证据） |");
L.push("| 与既有测试的关系 | 项目自带 328 个 Java 测试另行执行（328/328 通过），本库只收本轮新增的黑盒用例 |");
L.push("| 重测覆盖 | 部分用例在执行中重测过（E2 分三轮、E4 分三批），本库对同编号取最后一次判定 |");
L.push("| 已知差异 | E4 有 7 条用例经复核判定为测试自身问题而非产品缺陷（见 05 执行记录 §6），本库保留其最后判定原文，未做美化 |");
L.push("");
L.push("## 1. 总量（去重后）");
L.push("");
L.push("| 指标 | 数值 |");
L.push("|---|---|");
L.push("| 用例数 | **" + total + "** |");
L.push("| 通过 | " + pass + " |");
L.push("| 失败 | " + fail + " |");
L.push("| 阻塞 | " + block + " |");
L.push("| 通过率（按已执行） | " + ((pass / (total - block)) * 100).toFixed(1) + "% |");
L.push("");
L.push("> 各流自报的执行规模略大于本库去重后的条数（E1 223 / E2 134 / E3 65 / E4 68，合计 490 条执行），差额来自跨轮重测与作废批次；两种口径都在 05 执行记录中列明。");
L.push("");
L.push("## 2. 分工作流");
L.push("");
L.push("| 流 | 主题 | 用例 | 通过 | 失败 | 阻塞 |");
L.push("|---|---|---|---|---|---|");
for (const k of ["E1","E2","E3","E4"]) { const v = byStream[k]; if (v) L.push("| " + k + " | " + STREAM[k] + " | " + v.total + " | " + v.pass + " | " + v.fail + " | " + v.block + " |"); }
L.push("| 合计 | - | **" + total + "** | **" + pass + "** | **" + fail + "** | **" + block + "** |");
L.push("");
L.push("## 3. 分模块");
L.push("");
L.push("| 模块 | 用例 | 通过 | 失败 | 通过率 |");
L.push("|---|---|---|---|---|");
for (const k of Object.keys(byMod).sort((a, b) => byMod[b].total - byMod[a].total)) { const v = byMod[k]; L.push("| " + (MOD[k] || k) + " | " + v.total + " | " + v.pass + " | " + v.fail + " | " + ((v.pass / v.total) * 100).toFixed(1) + "% |"); }
L.push("");
L.push("## 4. 全量用例清单");
for (const s of ["E1","E2","E3","E4"]) {
  const rows = cases.filter(c => c.stream === s);
  L.push("");
  L.push("### " + s + " · " + STREAM[s] + "（" + rows.length + " 条）");
  L.push("");
  L.push("| 原始编号 | 模块 | 用例 | 结论 |");
  L.push("|---|---|---|---|");
  for (const c of rows) L.push("| " + c.orig + " | " + c.module + " | " + String(c.title || "").replace(/\|/g, "/").slice(0, 90) + " | " + (c.result === "通过" ? "通过" : c.result) + " |");
}
