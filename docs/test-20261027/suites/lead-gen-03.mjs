
import fs from 'node:fs';
import path from 'node:path';
const OUT = "D:\\work\\知识库\\docs\\test-20261027";
const cases = JSON.parse(fs.readFileSync(path.join(OUT, "evidence", "lead", "cases-normalized.json"), "utf8"));
const STREAM = { E1: "API 与业务功能", E2: "安全", E3: "性能与容量", E4: "界面 E2E", E5: "需求/文档一致性" };
const MOD = { AUTH: "AUTH 认证", ADMIN: "ADMIN 管理", FOLDER: "FOLDER 目录", NOTE: "NOTE 笔记", SEARCH: "SEARCH 搜索", TAG: "TAG 标签", LINK: "LINK 双链", VERSION: "VERSION 版本", TRASH: "TRASH 回收站", FILE: "FILE 附件", IMPEXP: "IMPEXP 导入导出", STAT: "STAT 统计", NF: "NF 非功能", EXPORT: "EXPORT 导出", UI: "UI 界面", BRIEF: "BRIEF 简报" };
const tally = (arr, k) => { const m = {}; for (const c of arr) { const key = c[k]; m[key] = m[key] || { total: 0, pass: 0, fail: 0, block: 0 }; m[key].total++; if (c.result === "通过") m[key].pass++; else if (c.result === "失败") m[key].fail++; else m[key].block++; } return m; };
const byStream = tally(cases, "stream"), byMod = tally(cases, "module");
const total = cases.length, pass = cases.filter(c => c.result === "通过").length, fail = cases.filter(c => c.result === "失败").length, block = cases.filter(c => c.result === "阻塞").length;
const L = [];
L.push("# 03 测试用例库");
L.push("");
L.push("> 本文件是 4 条执行流产出的用例编号级索引（去重后 " + total + " 条）。每条用例的完整断言与真实响应，见 evidence 目录下各流原始记录。");
L.push("> 机读版：03-测试用例库.csv（UTF-8 BOM，可直接用 Excel 打开）。");
